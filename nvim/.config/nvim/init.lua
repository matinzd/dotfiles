-- SECTION 6: LSP
-- LSP keymaps, server configuration, Mason tools installations
-- ============================================================
do
  -- Useful status updates for LSP.
  vim.pack.add { gh 'j-hui/fidget.nvim' }
  require('fidget').setup {}

  vim.api.nvim_create_autocmd('LspAttach', {
    group = vim.api.nvim_create_augroup('kickstart-lsp-attach', { clear = true }),
    callback = function(event)
      local map = function(keys, func, desc, mode)
        mode = mode or 'n'
        vim.keymap.set(mode, keys, func, { buffer = event.buf, desc = 'LSP: ' .. desc })
      end

      map('grn', vim.lsp.buf.rename, '[R]e[n]ame')
      map('gra', vim.lsp.buf.code_action, '[G]oto Code [A]ction', { 'n', 'x' })
      map('grD', vim.lsp.buf.declaration, '[G]oto [D]eclaration')

      -- Highlight references of the word under the cursor on CursorHold,
      -- and clear them when the cursor moves.
      local client = vim.lsp.get_client_by_id(event.data.client_id)
      if client and client:supports_method('textDocument/documentHighlight', event.buf) then
        local highlight_augroup = vim.api.nvim_create_augroup('kickstart-lsp-highlight', { clear = false })
        vim.api.nvim_create_autocmd({ 'CursorHold', 'CursorHoldI' }, {
          buffer = event.buf,
          group = highlight_augroup,
          callback = vim.lsp.buf.document_highlight,
        })

        vim.api.nvim_create_autocmd({ 'CursorMoved', 'CursorMovedI' }, {
          buffer = event.buf,
          group = highlight_augroup,
          callback = vim.lsp.buf.clear_references,
        })

        vim.api.nvim_create_autocmd('LspDetach', {
          group = vim.api.nvim_create_augroup('kickstart-lsp-detach', { clear = true }),
          callback = function(event2)
            vim.lsp.buf.clear_references()
            vim.api.nvim_clear_autocmds { group = 'kickstart-lsp-highlight', buffer = event2.buf }
          end,
        })
      end

      if client and client:supports_method('textDocument/inlayHint', event.buf) then
        map('<leader>th', function() vim.lsp.inlay_hint.enable(not vim.lsp.inlay_hint.is_enabled { bufnr = event.buf }) end, '[T]oggle Inlay [H]ints')
      end
    end,
  })

  ---@type table<string, vim.lsp.Config>
  local servers = {
    ts_ls = {
      -- Don't attach in Flow projects -- `flow` (below) owns those.
      root_dir = function(bufnr, on_dir)
        local fname = vim.api.nvim_buf_get_name(bufnr)
        if vim.fs.find('.flowconfig', { path = vim.fs.dirname(fname), upward = true })[1] then return end
        on_dir(vim.fs.root(bufnr, { 'tsconfig.json', 'jsconfig.json', 'package.json', '.git' }))
      end,
    },

    -- Flow: uses the `flow` binary from the project's node_modules (via npx),
    -- so there is nothing for Mason to install (see `ignore_install` below).
    flow = {},

    -- Android
    -- JetBrains' official Kotlin LSP -- same IntelliJ/Kotlin-plugin analysis engine
    -- Android Studio uses. Ships its own JBR, so it does not care which JDK is on
    -- PATH (the old fwcd `kotlin_language_server` shelled out to Gradle and broke
    -- on JDK 21 vs Gradle 7.x: "Unsupported class file major version 65").
    kotlin_lsp = {
      -- Pick the OUTERMOST Gradle root inside the repo, not the nearest one.
      -- lspconfig's default stops at the first `settings.gradle[.kts]` walking up,
      -- which in composite builds (e.g. the react-native monorepo) lands on an
      -- inner project that cannot be imported standalone -- its plugin versions
      -- come from the outer build's `includeBuild(...)` substitution, so the
      -- import dies with "Could not find <plugin>:" and an empty version.
      root_dir = function(bufnr, on_dir)
        local start = vim.fs.dirname(vim.api.nvim_buf_get_name(bufnr))
        local repo = vim.fs.root(bufnr, '.git')
        local outermost
        for _, marker in ipairs { 'settings.gradle.kts', 'settings.gradle', 'pom.xml' } do
          for _, found in ipairs(vim.fs.find(marker, { path = start, upward = true, limit = math.huge })) do
            local dir = vim.fs.dirname(found)
            -- Never escape the repo, and prefer the shallowest match
            if (not repo or dir:sub(1, #repo) == repo) and (not outermost or #dir < #outermost) then outermost = dir end
          end
        end
        on_dir(outermost or vim.fs.root(bufnr, { 'build.gradle.kts', 'build.gradle', '.git' }))
      end,
    },
    jdtls = {
      -- Include Gradle/Maven markers so it picks the Android project root, not a submodule
      root_markers = { 'settings.gradle', 'settings.gradle.kts', 'build.gradle', 'build.gradle.kts', 'pom.xml', '.git' },
    },

    -- iOS: sourcekit-lsp ships with the Xcode toolchain (no Mason package, see
    -- `ignore_install`). Needs a `buildServer.json` (generate one with
    -- `xcode-build-server config -project MyApp.xcodeproj -scheme MyApp`) for
    -- full indexing in .xcodeproj/.xcworkspace projects; SwiftPM works as-is.
    sourcekit = {},

    stylua = {}, -- Used to format Lua code

    lua_ls = {
      on_init = function(client)
        client.server_capabilities.documentFormattingProvider = false -- Disable formatting (formatting is done by stylua)

        if client.workspace_folders then
          local path = client.workspace_folders[1].name
          if path ~= vim.fn.stdpath 'config' and (vim.uv.fs_stat(path .. '/.luarc.json') or vim.uv.fs_stat(path .. '/.luarc.jsonc')) then return end
        end

        local current_settings = client.config.settings --[[@as lspconfig.settings.lua_ls]]
        client.config.settings.Lua = vim.tbl_deep_extend('force', current_settings.Lua, {
          runtime = {
            version = 'LuaJIT',
            path = { 'lua/?.lua', 'lua/?/init.lua' },
          },
          workspace = {
            checkThirdParty = false,
            -- NOTE: this is a lot slower and will cause issues when working on your own configuration.
            --  See https://github.com/neovim/nvim-lspconfig/issues/3189
            library = vim.api.nvim_get_runtime_file('', true),
          },
        })
      end,
      ---@type lspconfig.settings.lua_ls
      settings = {
        Lua = {
          format = { enable = false }, -- Disable formatting (formatting is done by stylua)
        },
      },
    },
  }

  vim.pack.add {
    gh 'neovim/nvim-lspconfig',
    gh 'mason-org/mason.nvim',
    gh 'mason-org/mason-lspconfig.nvim',
    gh 'WhoIsSethDaniel/mason-tool-installer.nvim',
  }

  require('mason').setup {}

  require('mason-lspconfig').setup {
    automatic_enable = false,
  }

  -- Servers that have no Mason package (provided by the project itself)
  local ignore_install = { flow = true, sourcekit = true }

  local ensure_installed = vim.tbl_filter(function(name) return not ignore_install[name] end, vim.tbl_keys(servers or {}))
  vim.list_extend(ensure_installed, {
    'ktlint', -- Kotlin formatter/linter
    'google-java-format', -- Java formatter
    'prettierd', -- JS/TS formatter
  })

  require('mason-tool-installer').setup { ensure_installed = ensure_installed }

  for name, server in pairs(servers) do
    vim.lsp.config(name, server)
    vim.lsp.enable(name)
  end
end

